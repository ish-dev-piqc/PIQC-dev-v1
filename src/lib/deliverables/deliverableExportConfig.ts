// =============================================================================
// deliverableExportConfig — per-artifact export vocabulary for the portrait
// PDF builder (buildDeliverablePdf). One exhaustive
// Record<DeliverableArtifactType, …> so adding a sixth artifact type cannot
// compile without describing how it exports — the same type-forced discipline
// the panel's DELIVERABLE_CONFIGS / DELIVERABLE_COPY use.
//
// Lives in the lib layer (imports only types/deliverables) so the export API
// stays free of any src/components import.
//
// Draft-only doctrine, enforced structurally + by test:
//   - every headerLabel carries "PIQC drafted · … · DRAFT";
//   - every disclaimer carries the compliance tokens (source-backed · draft ·
//     outside PIQC) and never uses approval vocabulary.
//
// siv_package has an entry for completeness (filename slug + a future portrait
// path), but the SIV deck ships through its own landscape builder
// (exporters/buildSivDeck) with its own header/disclaimer; only the filename
// helper is shared.
// =============================================================================

export interface DeliverableExportConfig {
  /** Render order for the PDF's per-section tables. */
  sectionOrder: readonly string[];
  sectionLabels: Record<string, string>;
  /** Middle segment of the filename: <code>_<slug>_draft_<date>.pdf. */
  filenameSlug: string;
  /** Corner/header band label. */
  headerLabel: string;
  /** Footer disclaimer — draft-only, source-backed, control-stays-outside-PIQC. */
  disclaimer: string;
}

