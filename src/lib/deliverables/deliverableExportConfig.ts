/** Narrowing guard for a server-supplied artifact_type string — the whitelist
 *  is the config's own keys (whitelist-from-the-map, never a hand-listed set
 *  that silently goes stale). */
export function isExportableArtifactType(value: unknown): value is DeliverableArtifactType {
  return typeof value === 'string' &&
    Object.prototype.hasOwnProperty.call(DELIVERABLE_EXPORT_CONFIGS, value);
}
