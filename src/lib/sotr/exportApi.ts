// Source of Truth Reviewer — Draft Confidence Packet export (PR-6).
//
// Three layers, each separately testable:
//
//   1. fetchDraftConfidencePacket — RPC call, study-scoped, RLS enforced.
//   2. buildDraftConfidencePacketCsv — pure function, JSON → CSV string.
//   3. downloadDraftConfidencePacket — orchestrates fetch + build + Blob/click.
//
// PIQC is a drafting + review aid. The CSV always opens with a clear
// disclaimer. Naming uses "draft confidence" deliberately — never
// "approved" / "signed" / "certified".
