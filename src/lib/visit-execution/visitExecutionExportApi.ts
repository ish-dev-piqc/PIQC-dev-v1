/**
 * Mock-mode synthetic packet builder. Pulls the requested visit from the
 * mock workspace fixture and shapes it into the export packet — same
 * structure the real RPC returns, so demos download a real PDF.
 *
 * Returns null when the visit_template_id isn't in the fixture (e.g. wrong
 * protocol id passed in mock mode).
 */
function buildMockPacket(visitTemplateId: string): VisitWorksheetExportPacket | null {
  // Mock fixture is keyed by protocol id. We only have a visit_template_id
  // here, so scan all known demo protocols for the requested visit. The
  // fixtures are tiny; scanning is fine. BRIGHTEN-2 is the canonical demo
  // (Sprint 1 ships visits under it); the other two are listed so a future
  // multi-protocol fixture doesn't require touching this file.
  const protocolIds: string[] = [
    DEMO_PROTOCOL_IDS['BRIGHTEN-2'],
    DEMO_PROTOCOL_IDS['CARDIAC-7'],
    DEMO_PROTOCOL_IDS['IMMUNE-14'],
  ];
  let workspace = null;
  let foundProtocolId: string | null = null;
  for (const pid of protocolIds) {
    const match = getMockVisitExecutionWorkspaces(pid).find(
      (w) => w.visit_template_id === visitTemplateId,
    );
    if (match) {
      workspace = match;
      foundProtocolId = pid;
      break;
    }
  }
  if (!workspace || !foundProtocolId) return null;

  // Map the demo protocol UUID back to its human code for the filename.
  const protocolCode =
    (Object.entries(DEMO_PROTOCOL_IDS).find(([, id]) => id === foundProtocolId)?.[0]) ?? null;

  return {
    protocol_id: workspace.protocol_id,
    protocol_code: protocolCode,
    protocol_title: `${protocolCode ?? 'Demo protocol'} (mock fixture)`,
    visit_template_id: workspace.visit_template_id,
    generated_at: new Date().toISOString(),
    snapshot: {
      visit_name: workspace.snapshot.visit_name,
      study_day: workspace.snapshot.study_day,
      window_minus_days: workspace.snapshot.window_minus_days,
      window_plus_days: workspace.snapshot.window_plus_days,
      purpose: workspace.snapshot.purpose,
      is_dosing_visit: workspace.snapshot.is_dosing_visit,
      has_primary_endpoint: workspace.snapshot.has_primary_endpoint,
      has_safety_critical: workspace.snapshot.has_safety_critical,
      item_count: workspace.snapshot.item_count,
      reviewed_count: workspace.snapshot.reviewed_count,
      needs_review_count: workspace.snapshot.needs_review_count,
      amendment_version: workspace.snapshot.amendment_version,
      confidence_state: workspace.snapshot.confidence_state,
      completeness_signal_count: workspace.snapshot.completeness_signal_count,
    },
    items: workspace.items.map((item, idx) => ({
      id: item.id,
      phase: item.phase,
      phase_order: idx + 1,
      ordinal: idx + 1,
      label: item.label,
      description: item.description,
      classification: item.classification,
      role_hint: item.role_hint,
      review_status: item.review_status,
      review_note: item.review_note,
      // Mock fixture has no `origin` field; treat as parser-derived.
      origin: 'soa_cell' as const,
      conditions: item.conditions,
      timing: item.timing,
      source_fields: item.source_fields,
      confidence_state: item.confidence_state,
      traceability: {
        soa_column: item.traceability.soa_column,
        protocol_section: item.traceability.protocol_section,
        protocol_page: item.traceability.protocol_page,
        amendment_version: item.traceability.amendment_version,
      },
    })),
  };
}

/**
 * Fetch the worksheet packet for one visit.
 *
 * Mock-mode short-circuits with a synthetic packet (so demos download a
 * real PDF). Real-mode wraps the RPC + defensive narrowing.
 */
export async function fetchVisitWorksheetPacket(
  visitTemplateId: string,
): Promise<Result<VisitWorksheetExportPacket>> {
  if (isMockEnabled()) {
    const packet = buildMockPacket(visitTemplateId);
    if (!packet) {
      return { ok: false, error: 'No mock fixture for this visit' };
    }
    return { ok: true, data: packet };
  }

  const { data, error } = await supabase.rpc('visit_execution_export_worksheet', {
    p_visit_template_id: visitTemplateId,
  });

  if (error) {
    return { ok: false, error: error.message };
  }

  // Defensive shape check at the boundary. Per Sprint 4c lesson: drop rather
  // than crash.
  const payload = data as Partial<VisitWorksheetExportPacket> | null;
  if (
    !payload ||
    typeof payload.protocol_id !== 'string' ||
    typeof payload.visit_template_id !== 'string' ||
    typeof payload.generated_at !== 'string' ||
    !payload.snapshot ||
    !Array.isArray(payload.items)
  ) {
    return { ok: false, error: 'malformed worksheet packet' };
  }

  return {
    ok: true,
    data: {
      protocol_id: payload.protocol_id,
      protocol_code: typeof payload.protocol_code === 'string' ? payload.protocol_code : null,
      protocol_title:
        typeof payload.protocol_title === 'string' ? payload.protocol_title : 'Untitled protocol',
      visit_template_id: payload.visit_template_id,
      generated_at: payload.generated_at,
      snapshot: payload.snapshot,
      items: payload.items,
    },
  };
}

