/**
 * Format the timing constraint for a print row. Returns "—" when no timing.
 */
function formatTiming(row: VisitWorksheetExportRow): string {
  if (!row.timing) return '—';
  const t = row.timing;
  // Hard-constraint label gets a "!" flag for at-a-glance differentiation.
  const flag = t.is_hard_constraint ? '! ' : '';
  return `${flag}${t.label}`;
}

/**
 * Build a multi-line "Requirement" cell: label + (optional) description +
 * inline conditional rules + inline source fields. Returns a single string
 * with \n separators — autotable handles wrapping.
 */
function formatRequirementCell(row: VisitWorksheetExportRow): string {
  const lines: string[] = [row.label];

  if (row.description) {
    lines.push(row.description);
  }

  for (const c of row.conditions) {
    lines.push(`If: ${c.condition_text}`);
    lines.push(`Then: ${c.consequence_text}`);
  }

  if (row.source_fields.length > 0) {
    const fields = row.source_fields
      .map((f) => `${f.field_label}${f.units ? ` (${f.units})` : ''}${f.is_required ? '*' : ''}`)
      .join(', ');
    lines.push(`Source fields: ${fields}`);
  }

  if (row.review_note) {
    lines.push(`Site note: ${row.review_note}`);
  }

  // Add a marker for human-added rows so coordinators can see at a glance
  // which items came from PIQC's draft vs were added during review.
  if (row.origin === 'human_added') {
    lines.push('(Coordinator-added during review)');
  }

  return lines.join('\n');
}

/**
 * Format the study-day + window into one print-friendly line.
 */
function formatWindow(snapshot: VisitWorksheetExportPacket['snapshot']): string {
  const day = snapshot.study_day >= 0 ? `+${snapshot.study_day}` : `${snapshot.study_day}`;
  if (snapshot.window_minus_days === 0 && snapshot.window_plus_days === 0) {
    return `Day ${day} · fixed (no permissible window)`;
  }
  if (snapshot.window_minus_days === snapshot.window_plus_days) {
    return `Day ${day} · ± ${snapshot.window_plus_days} day${snapshot.window_plus_days === 1 ? '' : 's'}`;
  }
  return `Day ${day} · −${snapshot.window_minus_days} / +${snapshot.window_plus_days} days`;
}

/**
 * Format the server-stamped timestamp into a "Generated YYYY-MM-DD HH:MM UTC"
 * line for the PDF footer.
 */
function formatGeneratedAt(iso: string): string {
  try {
    const d = new Date(iso);
    if (Number.isNaN(d.getTime())) return iso;
    const y = d.getUTCFullYear();
    const mo = String(d.getUTCMonth() + 1).padStart(2, '0');
    const day = String(d.getUTCDate()).padStart(2, '0');
    const hh = String(d.getUTCHours()).padStart(2, '0');
    const mm = String(d.getUTCMinutes()).padStart(2, '0');
    return `Generated ${y}-${mo}-${day} ${hh}:${mm} UTC`;
  } catch {
    return iso;
  }
}

/**
 * Pure function: packet → jsPDF document.
 *
 * Layout (US Letter portrait):
 *   - First page only: title block (visit name + window + purpose + stats)
 *   - All pages: header band ("PIQC drafted · Visit worksheet · DRAFT")
 *                + footer band (disclaimer + Generated <ts> + page X/Y)
 *   - Body: one autotable per non-empty phase
 *   - Last: traceability appendix (per-item protocol section + page)
 *
 * Sprint 6 — when `roleFilter` is non-`'all'`:
 *   - Items filtered (in-place packet not mutated; filtered local view used)
 *   - Title block gets a "Filtered view: <Role>" subtitle line
 *   - Stats line scopes to filtered counts
 *   - Open-items warning banner scopes to filtered counts
 *   - Traceability appendix scopes to filtered items
 *
 * Returns the jsPDF instance so callers can .save() / .output() / inspect
 * in tests.
 */
export function buildVisitWorksheetPdf(
  packet: VisitWorksheetExportPacket,
  roleFilter: RoleFilter = 'all',
): jsPDF {
  const doc = new jsPDF({ unit: 'pt', format: 'letter', orientation: 'portrait' });
  const pageWidth = doc.internal.pageSize.getWidth();
  const pageHeight = doc.internal.pageSize.getHeight();
  const margin = 48; // 0.67" — gives autotable room to breathe.

  const phaseLabels = packet.snapshot.is_dosing_visit
    ? PHASE_LABELS_DOSING
    : PHASE_LABELS_NON_DOSING;

  // Sprint 6: apply the role lens. Filter the items list and recompute
  // the snapshot counts so the title block + banner + stats line
  // reflect what's actually on the page. The packet is NOT mutated; the
  // original totals stay accessible for tests / future re-renders.
  //
  // VisitWorksheetExportRow exposes role_hint directly (see types file),
  // so the filter is a simple substring match via the canonical
  // itemMatchesRoleFilter helper. Unscoped rows (null role_hint / "Site
  // staff" / etc.) appear under every role — clinical-default safety.
  const isFiltered = roleFilter !== 'all';
  const filteredItems = isFiltered
    ? packet.items.filter((i) => itemMatchesRoleFilter(i.role_hint, roleFilter))
    : packet.items;
  const filteredReviewedCount = isFiltered
    ? filteredItems.filter((i) => i.review_status === 'reviewed').length
    : packet.snapshot.reviewed_count;
  const filteredNeedsReviewCount = isFiltered
    ? filteredItems.filter(
        (i) => i.review_status === 'not_reviewed' || i.review_status === 'needs_review',
      ).length
    : packet.snapshot.needs_review_count;

  // ---- Title block (first page) -------------------------------------------
  let cursorY = margin + 28;

  doc.setFont('helvetica', 'bold');
  doc.setFontSize(9);
  doc.setTextColor(120);
  doc.text(WORKSHEET_HEADER_LABEL, margin, margin);

  doc.setTextColor(20);
  doc.setFontSize(18);
  doc.text(packet.snapshot.visit_name, margin, cursorY);
  cursorY += 22;

  doc.setFont('helvetica', 'normal');
  doc.setFontSize(11);
  doc.setTextColor(60);
  doc.text(formatWindow(packet.snapshot), margin, cursorY);
  cursorY += 16;

  doc.setFontSize(9);
  doc.setTextColor(110);
  // Protocol title + code on one line. NO sponsor — sponsor-name-free.
  const codeLabel = packet.protocol_code
    ? `${packet.protocol_title} · ${packet.protocol_code}`
    : packet.protocol_title;
  doc.text(codeLabel, margin, cursorY);
  cursorY += 16;

  // Sprint 6: filtered-view subtitle. Only renders when a role lens is
  // active. Sits between the protocol-code line and the purpose section
  // so a coordinator scanning the page knows immediately "this is the
  // <Role> view of the worksheet, not the full visit."
  // Sprint 7: derived visit-level confidence. Computed against the
  // already-filtered item set so the rollup matches what the PDF actually
  // contains. Surfaced as a label line below the protocol-title/code line
  // and again in the title block when the rollup is non-'high' (cognitive-
  // load discipline). Per-item confidence renders in the autotable column
  // below.
  //
  // Coordinator-facing intent (re-confirmed 2026-05-30): the coordinator
  // handing off the worksheet should KNOW PIQC's confidence in the
  // underlying extraction, not have to guess. Hiding the indicator while
  // per-item confidence is improving would treat a symptom.
  const visitConfidence = deriveVisitConfidence(packet.snapshot, filteredItems);

  // `isFiltered` already implies `roleFilter !== 'all'`; second check
  // would be redundant. The inner narrow uses a type-only guard cast
  // because TypeScript can't trace the equivalence across the variable.
  if (isFiltered) {
    doc.setFont('helvetica', 'bold');
    doc.setFontSize(9);
    // Blue-800 (approx 30, 64, 175) — matches the existing TimingBanner
    // informational accent. Avoids introducing a NEW color (indigo would
    // have) for a label that serves the same "informational, not
    // warning" semantic role.
    doc.setTextColor(30, 64, 175);
    doc.text(
      `Filtered view: ${ROLE_LABELS[roleFilter as Exclude<RoleFilter, 'all'>]}`,
      margin,
      cursorY,
    );
    doc.setFont('helvetica', 'normal');
    cursorY += 14;
  }

  // Sprint 7: visit-level confidence label. Always shown — the deliverable
  // is the moment-of-lock-in and the coordinator handing it off should
  // KNOW PIQC's confidence in the underlying extraction, not have to
  // guess.
  //
  // Color discipline (post-design-critique): only alarm states earn
  // color in the PDF. high + medium use the default protocol-code gray;
  // low + needs_review get amber + rose accents. Matches the polish-v2
  // "rare-loud states earn pixels" rule applied across the workspace.
  //
  // Copy uses short labels + agentic attribution: "PIQC confidence: High"
  // vs the repetitive "Confidence: High confidence" that the long-label
  // form produced.
  doc.setFont('helvetica', 'bold');
  doc.setFontSize(9);
  const isAlarmConfidence =
    visitConfidence === 'low' || visitConfidence === 'needs_review';
  if (isAlarmConfidence) {
    const confidenceColor: [number, number, number] =
      visitConfidence === 'low'
        ? [180, 83, 9]     // amber-700
        : [190, 18, 60];   // rose-700
    doc.setTextColor(confidenceColor[0], confidenceColor[1], confidenceColor[2]);
  } else {
    doc.setTextColor(60); // quiet gray for high/medium (baseline)
  }
  doc.text(
    `PIQC confidence: ${CONFIDENCE_SHORT_LABELS[visitConfidence]}`,
    margin,
    cursorY,
  );
  doc.setFont('helvetica', 'normal');
  doc.setTextColor(60);
  cursorY += 18;

  // Purpose section — placeholder-aware. When the RPC returned the canonical
  // fallback string (parser hasn't extracted a real purpose yet), we frame
  // it explicitly as parser-pending in italic gray so the deliverable
  // doesn't read as "unfinished by the coordinator." When the prose is
  // real, render it as a normal-weight body block.
  doc.setFontSize(8);
  doc.setTextColor(110);
  doc.text('PIQC DRAFTED', margin, cursorY);
  cursorY += 12;
  const isPlaceholderPurpose = packet.snapshot.purpose.trim() === WORKSHEET_PLACEHOLDER_PURPOSE;
  if (isPlaceholderPurpose) {
    doc.setFont('helvetica', 'italic');
    doc.setFontSize(10);
    doc.setTextColor(120);
    const placeholderText =
      'Visit purpose not yet extracted from the protocol. Re-run ingest or fill in the workspace before relying on this draft.';
    const placeholderLines = doc.splitTextToSize(placeholderText, pageWidth - margin * 2);
    doc.text(placeholderLines, margin, cursorY);
    cursorY += placeholderLines.length * 12 + 14;
    doc.setFont('helvetica', 'normal');
  } else {
    doc.setFontSize(10);
    doc.setTextColor(40);
    const purposeLines = doc.splitTextToSize(packet.snapshot.purpose, pageWidth - margin * 2);
    doc.text(purposeLines, margin, cursorY);
    cursorY += purposeLines.length * 12 + 14;
  }

  // Stats line. The "to review" count is colored amber when non-zero so a
  // coordinator scanning the stats line sees open work at a glance.
  // Sprint 6: when filtered, counts scope to the visible item set so the
  // numbers describe what's actually on the page below them.
  const statsItemCount = isFiltered ? filteredItems.length : packet.snapshot.item_count;
  const statsReviewedCount = filteredReviewedCount;
  const statsNeedsReviewCount = filteredNeedsReviewCount;

  doc.setFontSize(9);
  doc.setTextColor(60);
  const baseStatsLine = `${statsItemCount} requirements · ${statsReviewedCount} reviewed · `;
  doc.text(baseStatsLine, margin, cursorY);
  const baseWidth = doc.getTextWidth(baseStatsLine);

  if (statsNeedsReviewCount > 0) {
    // Approximate Tailwind amber-700 (#B45309) — RGB tuned for print
    // contrast on white paper. Exact match isn't required since the PDF
    // viewer's rendering already shifts gamma; this reads clearly amber.
    doc.setTextColor(180, 83, 9);
    doc.setFont('helvetica', 'bold');
  }
  doc.text(`${statsNeedsReviewCount} to review`, margin + baseWidth, cursorY);
  doc.setFont('helvetica', 'normal');
  doc.setTextColor(60);

  if (packet.snapshot.amendment_version) {
    const widthSoFar = baseWidth + doc.getTextWidth(`${statsNeedsReviewCount} to review`);
    doc.text(` · ${packet.snapshot.amendment_version}`, margin + widthSoFar, cursorY);
  }
  cursorY += 18;

  // Open-items warning banner. When N requirements still need review, the
  // coordinator must not mistake this artifact for a complete deliverable.
  // Sprint 6: scoped to filtered counts so a filtered view doesn't shout
  // about open items the role-view doesn't show.
  if (statsNeedsReviewCount > 0) {
    const bannerHeight = 28;
    const bannerY = cursorY;
    // Amber fill + border, matching the workspace's hard-constraint timing tone.
    doc.setFillColor(254, 243, 199); // amber-100
    doc.setDrawColor(252, 211, 77);  // amber-300
    doc.setLineWidth(0.8);
    doc.rect(margin, bannerY, pageWidth - margin * 2, bannerHeight, 'FD');

    doc.setTextColor(146, 64, 14); // amber-800
    doc.setFont('helvetica', 'bold');
    doc.setFontSize(9);
    const bannerLeadingX = margin + 8;
    doc.text('⚠', bannerLeadingX, bannerY + 12);
    doc.setFont('helvetica', 'normal');
    const bannerMessage =
      `${statsNeedsReviewCount} requirement${statsNeedsReviewCount === 1 ? '' : 's'} not yet reviewed. ` +
      'Continue reviewing in PIQC before relying on this draft.';
    const bannerLines = doc.splitTextToSize(
      bannerMessage,
      pageWidth - margin * 2 - 28,
    );
    doc.text(bannerLines, bannerLeadingX + 14, bannerY + 12);
    cursorY += bannerHeight + 14;
    // Reset color state for downstream content.
    doc.setTextColor(60);
    doc.setFont('helvetica', 'normal');
  } else {
    cursorY += 2;
  }

  // ---- Per-phase autotables ----------------------------------------------
  for (const phase of PHASE_ORDER) {
    // Sprint 6: phase grouping operates on the role-filtered view when a
    // role lens is active. Same hide-empty-phases behavior as before; just
    // downstream of the filter.
    const phaseItems = filteredItems.filter((i) => i.phase === phase);
    if (phaseItems.length === 0) continue;

    // Phase title
    doc.setFont('helvetica', 'bold');
    doc.setFontSize(11);
    doc.setTextColor(20);
    if (cursorY > pageHeight - margin - 80) {
      doc.addPage();
      cursorY = margin + 20;
    }
    doc.text(phaseLabels[phase], margin, cursorY);
    cursorY += 4;

    autoTable(doc, {
      startY: cursorY + 6,
      margin: { left: margin, right: margin },
      head: [['#', 'Requirement', 'Classification', 'Role', 'Timing', 'Status']],
      body: phaseItems.map((row, i) => [
        String(i + 1),
        formatRequirementCell(row),
        CLASSIFICATION_LABEL[row.classification],
        row.role_hint ?? '—',
        formatTiming(row),
        REVIEW_LABEL[row.review_status],
      ]),
      theme: 'grid',
      styles: {
        font: 'helvetica',
        fontSize: 8.5,
        cellPadding: 4,
        textColor: [30, 30, 30],
        lineColor: [220, 220, 220],
        lineWidth: 0.5,
      },
      headStyles: {
        fillColor: [240, 240, 240],
        textColor: [60, 60, 60],
        fontStyle: 'bold',
        fontSize: 8,
      },
      columnStyles: {
        0: { cellWidth: 22 },          // #
        1: { cellWidth: 'auto' },       // Requirement (multi-line)
        2: { cellWidth: 78 },           // Classification
        3: { cellWidth: 60 },           // Role
        4: { cellWidth: 62 },           // Timing
        5: { cellWidth: 60 },           // Status
      },
    });

    // After autotable, cursorY is whatever the table ended at. The
    // augmented `lastAutoTable` is patched onto the doc by jspdf-autotable
    // (see local JsPDFWithAutoTable type above).
    const augmented = doc as JsPDFWithAutoTable;
    const finalY = augmented.lastAutoTable?.finalY ?? cursorY + 100;
    cursorY = finalY + 20;
  }

  // ---- Traceability appendix ---------------------------------------------
  // One row per item with protocol_section + protocol_page. Keeps the audit
  // chain on the worksheet itself so the print artifact is self-contained.
  // Sprint 6: traceability appendix scopes to the filtered view so the
  // appendix doesn't reference rows the body of the worksheet doesn't show.
  const traceableItems = filteredItems.filter(
    (i) => i.traceability.protocol_section || i.traceability.protocol_page !== null,
  );
  if (traceableItems.length > 0) {
    if (cursorY > pageHeight - margin - 80) {
      doc.addPage();
      cursorY = margin + 20;
    }
    doc.setFont('helvetica', 'bold');
    doc.setFontSize(11);
    doc.setTextColor(20);
    doc.text('Traceability appendix', margin, cursorY);
    cursorY += 4;

    autoTable(doc, {
      startY: cursorY + 6,
      margin: { left: margin, right: margin },
      head: [['#', 'Requirement', 'Protocol section', 'Page', 'Amendment']],
      body: traceableItems.map((row, i) => [
        String(i + 1),
        row.label,
        row.traceability.protocol_section ?? '—',
        row.traceability.protocol_page !== null ? String(row.traceability.protocol_page) : '—',
        row.traceability.amendment_version ?? '—',
      ]),
      theme: 'grid',
      styles: {
        font: 'helvetica',
        fontSize: 8,
        cellPadding: 4,
        textColor: [60, 60, 60],
        lineColor: [220, 220, 220],
        lineWidth: 0.5,
      },
      headStyles: {
        fillColor: [240, 240, 240],
        textColor: [60, 60, 60],
        fontStyle: 'bold',
        fontSize: 8,
      },
      columnStyles: {
        0: { cellWidth: 22 },
        1: { cellWidth: 'auto' },
        2: { cellWidth: 130 },
        3: { cellWidth: 40 },
        4: { cellWidth: 80 },
      },
    });
  }

  // ---- DRAFT watermark + header + footer on every page ------------------
  // jsPDF doesn't have a "draw on every page" hook for autotable's added
  // pages; iterate after the body's done. The watermark is the compliance-
  // critical signal — the corner header label is too quiet for a printed
  // artifact that may be photocopied / faxed / scanned mid-stack. A 45°
  // diagonal "DRAFT" across each page is the standard clinical convention.
  const pageCount = doc.getNumberOfPages();
  for (let i = 1; i <= pageCount; i++) {
    doc.setPage(i);

    // Watermark — 45° diagonal "DRAFT" centered. NOTE: jsPDF has no
    // background-layer primitive, so the watermark is technically a
    // foreground layer drawn LAST. GState opacity makes it read visually
    // as a background (standard jsPDF watermark convention).
    //
    // Watermark visual weight (founder direction post-#141): kept quiet
    // so the coordinator's relationship with their freshly-exported
    // worksheet isn't undermined by an anxiety-inducing alarm. The
    // compliance signal is carried in depth by the corner label, footer
    // disclaimer, server-stamped timestamp, and open-items amber banner —
    // the watermark just needs to be present, not foreground-competing.
    //
    // Three compounding levers tune this:
    //   - Opacity 0.06  (half of Sprint 5's initial 0.12) — barely-there
    //   - Color (180,180,180) — light gray, washes further at low opacity
    //   - 90pt (down from 110pt) — diagonal still legible, less page-eating
    //
    // Result: discernible on purpose if you look for it; ignorable while
    // reading body content. GState reset to 1 after so subsequent
    // header/footer text renders fully opaque.
    const watermarkGState = doc.GState({ opacity: 0.06 });
    doc.setGState(watermarkGState);
    doc.setFont('helvetica', 'bold');
    doc.setFontSize(90);
    doc.setTextColor(180, 180, 180);
    doc.text('DRAFT', pageWidth / 2, pageHeight / 2, {
      align: 'center',
      angle: 45,
      baseline: 'middle',
    });
    // Reset opacity so subsequent header/footer text renders fully opaque.
    doc.setGState(doc.GState({ opacity: 1 }));

    // Header band — only show on pages 2+ (page 1 has the title block).
    if (i > 1) {
      doc.setFont('helvetica', 'bold');
      doc.setFontSize(8);
      doc.setTextColor(140);
      doc.text(WORKSHEET_HEADER_LABEL, margin, margin - 12);
      doc.setFont('helvetica', 'normal');
      doc.setTextColor(140);
      doc.text(packet.snapshot.visit_name, pageWidth - margin, margin - 12, { align: 'right' });
    }

    // Footer band — disclaimer left, generated_at + pagination right.
    // Bumped from 7pt → 8pt: the disclaimer is the most important line
    // on the deliverable; 7pt was at the readability floor.
    doc.setFont('helvetica', 'italic');
    doc.setFontSize(8);
    doc.setTextColor(120);
    const disclaimerLines = doc.splitTextToSize(WORKSHEET_DISCLAIMER, pageWidth - margin * 2 - 140);
    doc.text(disclaimerLines, margin, pageHeight - margin + 8);

    doc.setFont('helvetica', 'normal');
    doc.setFontSize(8);
    doc.text(formatGeneratedAt(packet.generated_at), pageWidth - margin, pageHeight - margin + 8, {
      align: 'right',
    });
    doc.text(`Page ${i} / ${pageCount}`, pageWidth - margin, pageHeight - margin + 20, {
      align: 'right',
    });
  }

  return doc;
}

